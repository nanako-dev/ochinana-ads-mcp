def stage_rank(stage: str) -> int:
    return STAGES.index(stage) if stage in STAGES else len(STAGES)


def order_actions(items: List[dict]) -> List[dict]:
    """候補を打ち手の段の順に並べ、入札・予算には「それでも不足なら」を付ける。同じ段の中は重い順。"""
    w = {"大": 0, "中": 1, "小": 2}
    items = sorted(items, key=lambda x: (stage_rank(x["段"]), w.get(x.get("重さ", "小"), 3)))
    for i, x in enumerate(items, 1):
        x["順"] = i
        if x["段"] == "入札・予算" and not str(x["案"]).startswith("それでも不足なら"):
            x["案"] = f"それでも不足なら: {x['案']}（必ず運用者の承認を取る）"
    return items
